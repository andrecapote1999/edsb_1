# MAGIC Last-minute flights (0-7 days) are the most expensive, with an average of $370.13, 12.6% more. So, for a traveller, booking 1 to 2 months before the flight saves on average around $41 per ticket compared to buying in the last week.
# MAGIC There are no prices for more than 60 days in advance, because in this dataset the flights were searched at most around 60 days before.

# COMMAND ----------

# MAGIC %md
# MAGIC ## 6.2 Question 2: cheapest routes, airlines and days
# MAGIC ### Cheapest routes from each airport
# MAGIC We calculate the average price and the percentage of direct flights for each route, and we rank the routes from each airport from the cheapest to the most expensive.
# MAGIC We only keep routes with at least 30 prices, so the average is reliable.
# MAGIC To create the ranking we use a **window function**: it calculates the rank inside each group of rows (here, each origin airport) without merging the rows.

# COMMAND ----------

# Average price per route and ranking of the cheapest routes from each airport (window function)

window_origin = Window.partitionBy("startingAirport").orderBy("avg_price")

gd_routes = sv.groupBy("route", "startingAirport", "destinationAirport", "destination_city") \
    .agg(count("*").alias("n_prices"),
         round(avg("totalFare"), 2).alias("avg_price"),
         round(avg(col("isNonStop").cast("int")) * 100, 1).alias("pct_nonstop"),
         round(avg("totalTravelDistance")).cast("int").alias("totalTravelDistance")) \
    .where(col("n_prices") >= 30) \
    .withColumn("rank", dense_rank().over(window_origin))

gd_routes.write.format("delta").mode("overwrite").option("overwriteSchema", "true").saveAsTable("flights.gd_routes")

# COMMAND ----------

