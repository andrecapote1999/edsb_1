# MAGIC %md
# MAGIC ## 5.1 New business columns
# MAGIC We create the columns we need for our questions:
# MAGIC * **route** - origin and destination airport together (ex: JFK-LAX)
# MAGIC * **days_in_advance** - days between the search and the flight
# MAGIC * **booking_window** - the days in advance grouped (0-7 days, 8-14 days, ...), to compare prices by group (Question 1)
# MAGIC * **weekday** - day of the week of the flight (Question 2)
# MAGIC * **airline** - the main airline. The column `segmentsAirlineName` has one airline for each part of the trip, separated by `||` (ex: `Delta||Delta`), we have decided to keep the first one

# COMMAND ----------


# Create the new business columns: route, days in advance, booking window, weekday and main airline
flights_sv = flights \
    .withColumn("route", concat_ws("-", "startingAirport", "destinationAirport")) \
    .withColumn("days_in_advance", datediff("flightDate", "searchDate")) \
    .withColumn("booking_window", when(col("days_in_advance") <= 7, "1. 0-7 days")
                                 .when(col("days_in_advance") <= 14, "2. 8-14 days")
                                 .when(col("days_in_advance") <= 30, "3. 15-30 days")
                                 .when(col("days_in_advance") <= 60, "4. 31-60 days")
                                 .otherwise("5. more than 60 days")) \
    .withColumn("weekday", date_format("flightDate", "E")) \
    .withColumn("airline", split("segmentsAirlineName", "\\|\\|").getItem(0))

# COMMAND ----------

# MAGIC %md
# MAGIC ## 5.2 Join with the airports
# MAGIC We join the flights with the airports table using the airport code (IATA), to get the origin and destination city names.
# MAGIC We do the join twice: once for the origin airport and once for the destination airport.
# MAGIC * **left join** - we keep all the flights, even if an airport is not found in the airports table
# MAGIC * **broadcast** - the airports table is small, so Spark copies it to every worker. This way the big flights table doesn't need to move between machines, which makes the join much faster

# COMMAND ----------

# Join with the airports to get the city names
# (airports is a small table, so we use broadcast: it is copied to all workers and the big table doesn't move)

origin = airports.select(col("iata").alias("startingAirport"), col("city").alias("origin_city"))
destination = airports.select(col("iata").alias("destinationAirport"), col("city").alias("destination_city"))

flights_sv = flights_sv \
    .join(broadcast(origin), "startingAirport", "left") \
    .join(broadcast(destination), "destinationAirport", "left") \
    .select("legId", "searchDate", "flightDate", "days_in_advance", "booking_window", "weekday",
            "route", "startingAirport", "origin_city", "destinationAirport", "destination_city",
            "airline", "isNonStop", "isBasicEconomy", "seatsRemaining", "totalTravelDistance", "totalFare")

